import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const { adminWebOperationContract, publicOperationContract } = require(
  path.join(repositoryRoot, 'cloudfunctions/mip-admin-api/domain/public-operation-contract.js'),
)

export const ADMIN_OPERATION_CONTRACT_ARTIFACT = 'src/modules/mip-admin/generated/admin-operation-contract.json'
export const ADMIN_OPERATION_CONTRACT_TYPES_ARTIFACT = 'packages/admin-contracts/src/generated/admin-operation-contract.ts'

export function renderAdminOperationContract() {
  return `${JSON.stringify(publicOperationContract, null, 2)}\n`
}

export function renderAdminOperationContractTypes() {
  return `/* eslint-disable style/comma-dangle, style/quote-props, style/quotes */\n// Generated by scripts/generate-admin-operation-contract.mjs. Do not edit.\n\nexport const ADMIN_OPERATION_CONTRACT = ${JSON.stringify(publicOperationContract, null, 2)} as const\n\nexport const ADMIN_WEB_OPERATION_CONTRACT = ${JSON.stringify(adminWebOperationContract, null, 2)} as const\n\nexport type AdminOperationContract = typeof ADMIN_OPERATION_CONTRACT\nexport type AdminOperation = AdminOperationContract['operations'][number]\nexport type AdminOperationKind = AdminOperation['kind']\nexport type AdminOperationAction = AdminOperation['action']\nexport type AdminQueryAction = Extract<AdminOperation, { kind: 'QUERY' }>['action']\nexport type AdminMutationAction = Extract<AdminOperation, { kind: 'MUTATION' }>['action']\n\nexport type AdminWebOperationContract = typeof ADMIN_WEB_OPERATION_CONTRACT\nexport type AdminWebOperation = AdminWebOperationContract['operations'][number]\nexport type AdminWebAllowedOperation = Extract<AdminWebOperation, { webAllowed: true }>\nexport type AdminWebOperationAction = AdminWebAllowedOperation['action']\nexport type AdminWebQueryAction = Extract<AdminWebAllowedOperation, { kind: 'QUERY' }>['action']\nexport type AdminWebMutationAction = Extract<AdminWebAllowedOperation, { kind: 'MUTATION' }>['action']\n`
}

function expectedArtifacts() {
  return [
    [ADMIN_OPERATION_CONTRACT_ARTIFACT, renderAdminOperationContract()],
    [ADMIN_OPERATION_CONTRACT_TYPES_ARTIFACT, renderAdminOperationContractTypes()],
  ]
}

export function assertAdminOperationContractArtifact(root = repositoryRoot) {
  for (const [relativePath, expected] of expectedArtifacts()) {
    const artifactPath = path.join(root, relativePath)
    if (!fs.existsSync(artifactPath)
      || fs.readFileSync(artifactPath, 'utf8') !== expected) {
      throw new Error('Admin operation contract artifact drifted; run node scripts/generate-admin-operation-contract.mjs --write')
    }
  }
}

export function writeAdminOperationContractArtifact(root = repositoryRoot) {
  const artifactPaths = expectedArtifacts().map(([relativePath, content]) => {
    const artifactPath = path.join(root, relativePath)
    fs.mkdirSync(path.dirname(artifactPath), { recursive: true })
    fs.writeFileSync(artifactPath, content, 'utf8')
    return artifactPath
  })
  return artifactPaths.join(', ')
}
