#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { resolve } from 'node:path'
import process from 'node:process'

const source = resolve('cloudfunctions/mip-admin-api/domain/role-template-policy.js')
const targets = ['mip-identity-api', 'mip-events-api', 'mip-tasks-api', 'mip-media-api', 'mip-game-api', 'mip-banners-api', 'mip-opportunities-api', 'mip-outbox-worker']
const expected = `// Generated by scripts/generate-role-template-policy.mjs. Do not edit.\n${readFileSync(source, 'utf8')}`
if (!['--write', '--check'].includes(process.argv[2])) {
  throw new Error('Use --write or --check')
}
for (const name of targets) {
  const path = resolve('cloudfunctions', name, 'lib/role-template-policy.js')
  if (process.argv[2] === '--write') {
    writeFileSync(path, expected)
  }
  else if (readFileSync(path, 'utf8') !== expected) {
    throw new Error(`Role authorization policy drift: ${name}`)
  }
}
console.log(`Role template policy ${process.argv[2]}: ${targets.length} self-contained consumers`)
const require = createRequire(import.meta.url)
const { roleCapabilities, isValidRoleBinding } = require(resolve('cloudfunctions/mip-admin-api/domain/capabilities.js'))
const { MEDIA_ADMIN_PURPOSE_CAPABILITIES } = require(resolve('cloudfunctions/mip-admin-api/domain/media.js'))
const uploadCapabilities = new Set(Object.values(MEDIA_ADMIN_PURPOSE_CAPABILITIES))
const uploadRoles = Object.fromEntries(Object.entries(roleCapabilities).map(([roleKey, capabilities]) => [roleKey, {
  capabilities: capabilities.filter(capability => uploadCapabilities.has(capability)),
  scopes: ['PLATFORM', 'BRANCH', 'EVENT'].filter(scopeType => isValidRoleBinding({ roleKey, scopeType, scopeId: scopeType === 'PLATFORM' ? null : '11111111-1111-4111-8111-111111111111' })),
}]))
const mediaPath = resolve('cloudfunctions/mip-media-api/lib/admin-upload-role-catalog.js')
const mediaSource = `// Generated by scripts/generate-role-template-policy.mjs from the admin capability owner. Do not edit.\n'use strict'\nmodule.exports = ${JSON.stringify(uploadRoles, null, 2)}\n`
if (process.argv[2] === '--write') {
  writeFileSync(mediaPath, mediaSource)
}
else if (readFileSync(mediaPath, 'utf8') !== mediaSource) {
  throw new Error('Media upload role capability catalog drift')
}
