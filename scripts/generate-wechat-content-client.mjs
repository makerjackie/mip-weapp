#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import process from 'node:process'

const source = resolve('cloudfunctions/mip-admin-api/lib/wechat-content-checker.js')
const target = resolve('cloudfunctions/mip-media-api/lib/wechat-content-checker.js')
const expected = `// Generated by scripts/generate-wechat-content-client.mjs. Do not edit.\n${readFileSync(source, 'utf8')}`
if (!['--write', '--check'].includes(process.argv[2])) {
  throw new Error('Use --write or --check')
}
if (process.argv[2] === '--write') {
  writeFileSync(target, expected)
}
else if (readFileSync(target, 'utf8') !== expected) {
  throw new Error('WeChat content safety client drift')
}
console.log(`WeChat content safety client ${process.argv[2]}: self-contained media consumer`)
